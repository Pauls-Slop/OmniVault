// Builds the web demo of the popup (for the project page): the real popup and background code as plain ES modules,
// with two files swapped – src/lib/browser.js (extension APIs, demo/browser.js) and src/providers/registry.js
// (simulated password managers with the real providers' metadata, demo/vault.js). No dependencies, no bundler.
// Usage: node demo/build.mjs [out-dir]   (default: dist/demo)
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const out = process.argv[2] ?? 'dist/demo';
const pkg = JSON.parse(await readFile('package.json', 'utf8'));

await rm(out, { recursive: true, force: true });
await mkdir(join(out, 'src/providers/bitwarden'), { recursive: true });
await mkdir(join(out, 'vendor'), { recursive: true });

// the extension code, unchanged
for (const dir of ['background', 'popup', 'lib', 'i18n', 'icons']) await cp(join('src', dir), join(out, 'src', dir), { recursive: true });
for (const f of ['provider.js', 'hosts.js', 'bitwarden/api.js']) await cp(join('src/providers', f), join(out, 'src/providers', f));
await cp('vendor/argon2id.mjs', join(out, 'vendor/argon2id.mjs')); // PIN unlock
for (const f of ['LICENSE', 'THIRD_PARTY_NOTICES.md']) await cp(f, join(out, f));

// metadata of the real providers (name, account form, capabilities), read from their classes
globalThis.chrome = { runtime: { getURL: (p) => p, id: 'build' }, storage: {} };
const { registry } = await import(new URL('../src/providers/registry.js', import.meta.url));
const FIELDS = ['id', 'label', 'status', 'note', 'configFields', 'unlockLabel', 'unlockOptions', 'unlockMode', 'optionalPermissions', 'capabilities'];
const meta = Object.fromEntries(Object.values(registry).map((p) => [p.id, Object.fromEntries(FIELDS.map((k) => [k, p[k]]))]));
await writeFile(join(out, 'src/providers/providers.json'), JSON.stringify(meta, null, 1));

// the registry itself stays the real one, only its provider imports become demo providers
let reg = await readFile('src/providers/registry.js', 'utf8');
let swapped = 0;
reg = reg.replace(/^import (\w+) from '\.\/([\w-]+)\/index\.js';$/gm, (_m, name, dir) => {
  if (!meta[dir]) throw new Error(`demo: no metadata for provider ${dir}`);
  swapped++;
  return `const ${name} = demoProvider(META[${JSON.stringify(dir)}]);`;
});
if (swapped !== Object.keys(meta).length) throw new Error(`demo: swapped ${swapped} of ${Object.keys(meta).length} providers in registry.js`);
reg = reg.replace(/^(import .*\n)(?!import)/m, `$1import { demoProvider } from './demo-vault.js';\nimport META from './providers.json' with { type: 'json' };\n`);
await writeFile(join(out, 'src/providers/registry.js'), `// Demo build: generated from src/providers/registry.js by demo/build.mjs\n${reg}`);

await cp('demo/browser.js', join(out, 'src/lib/browser.js'));
await cp('demo/vault.js', join(out, 'src/providers/demo-vault.js'));
await cp('demo/data.js', join(out, 'src/providers/demo-data.js'));

// the popup page: same markup, loaded through the demo entry
let html = await readFile('src/popup/popup.html', 'utf8');
if (!html.includes('href="popup.css"') || !html.includes('<script type="module" src="popup.js"></script>')) throw new Error('demo: popup.html changed, update demo/build.mjs');
html = html.replace('href="popup.css"', 'href="src/popup/popup.css"')
  .replace('<script type="module" src="popup.js"></script>', '<script type="module" src="main.js"></script>');
await writeFile(join(out, 'popup.html'), html);

await writeFile(join(out, 'main.js'), `// Demo entry (generated by demo/build.mjs): extension APIs, sample accounts, background, popup.
import { ext } from './src/lib/browser.js';
import { DEMO_ACCOUNTS } from './src/providers/demo-data.js';

globalThis.OMNIVAULT_DEMO_VERSION = ${JSON.stringify(pkg.version)};
const { accounts } = await ext.storage.local.get('accounts');
if (!accounts) { // first visit in this tab: the sample accounts, unlocked
  await ext.storage.local.set({ accounts: DEMO_ACCOUNTS });
  for (const a of DEMO_ACCOUNTS) await ext.storage.session.set({ ['session:' + a.id]: { demo: true } });
}
await import('./src/background/index.js');
await import('./src/popup/popup.js');
`);

for (const f of ['index.html', 'page.html']) await cp(join('demo', f), join(out, f));
console.log(`demo → ${out}`);
